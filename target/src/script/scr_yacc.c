	{
		yy_init = 0;
		if ( !yy_start )
		{
			yy_start = 1; /* first start state */
		}

		if ( !yyin )
		{
			yyin = stdin;
		}

		if ( !yyout )
		{
			yyout = stdout;
		}

		if ( !yy_current_buffer )
		{
			yy_current_buffer = yy_create_buffer(yyin, YY_BUF_SIZE);
		}

		yy_load_buffer_state();
	}

