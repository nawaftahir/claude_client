/*
==============
StringValue
==============
*/
int StringValue( char *str, int len )
{
	char *pC;
	char string[8192];

	if ( len >= 8192 )
	{
		CompileError(g_sourcePos, "max string length exceeded: \"%s\"", str);
		return 0;
	}

	pC = string;

	while ( len )
	{
		if ( *str != '\\' )
		{
			len--;
			*pC++ = *str++;
			continue;
		}

		len--;

		if ( !len )
			break;

		str++;

		switch ( *str )
		{
		case 'n':
			*pC++ = '\n';
			break;
		case 'r':
			*pC++ = '\r';
			break;
		case 't':
			*pC++ = '\t';
			break;
		default:
			*pC++ = *str;
			break;
		}

		len--;
		str++;
	}

	*pC = 0;

	yylval.val.stringValue = SL_GetString_(string, g_parse_user, 13);
	return 1;
}

